create or replace function public.admin_set_suggestion_status_v83(
  suggestion_id_input bigint,
  new_status text,
  award_points integer default 0,
  admin_comment_input text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  old_suggestion public.suggestions%rowtype;
  previous_points integer;
  next_points integer;
  clean_comment text := nullif(left(coalesce(admin_comment_input, ''), 500), '');
begin
  if not public.is_blank_space_admin() then raise exception 'Admin only.'; end if;
  if new_status not in ('pending','in_works','approved','denied','rejected') then raise exception 'Invalid suggestion status.'; end if;
  award_points := greatest(0, least(coalesce(award_points, 0), 10000));
  select * into old_suggestion from public.suggestions where id = suggestion_id_input for update;
  if not found then raise exception 'Suggestion not found.'; end if;
  previous_points := coalesce(old_suggestion.points_awarded, 0);
  next_points := case when new_status = 'approved' then award_points else 0 end;
  update public.profiles set points = greatest(0, coalesce(points,0) - previous_points + next_points) where id = old_suggestion.user_id;
  update public.suggestions set status = new_status, points_awarded = next_points, admin_comment = coalesce(clean_comment, admin_comment), decided_at = case when new_status in ('approved','denied','rejected') then now() else decided_at end where id = suggestion_id_input;
end;
$$;
