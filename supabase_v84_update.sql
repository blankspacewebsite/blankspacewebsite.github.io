create or replace function public.buy_icon_pack_v83(p_pack_id text, p_price integer, p_icon_id text, p_icon text, p_name text, p_rarity text)
returns void language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); current_points integer; clean_price integer:=greatest(1,least(coalesce(p_price,5),1000));
begin
  if uid is null then raise exception 'Not signed in.'; end if;
  if p_rarity not in ('common','uncommon','rare','epic','legendary','mythic','godly') then raise exception 'Bad rarity.'; end if;
  select points into current_points from public.profiles where id=uid for update;
  if coalesce(current_points,0) < clean_price then raise exception 'Not enough points.'; end if;
  update public.profiles set points=points-clean_price where id=uid;
  insert into public.user_icons(user_id, icon_id, icon, name, rarity) values(uid, p_icon_id, p_icon, p_name, p_rarity)
  on conflict(user_id, icon_id) do update set acquired_at=now();
end; $$;
grant execute on function public.buy_icon_pack_v83(text, integer, text, text, text, text) to authenticated;

create or replace function public.equip_owned_icon_v83(p_icon_id text)
returns void language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); chosen text;
begin
  if uid is null then raise exception 'Not signed in.'; end if;
  select icon into chosen from public.user_icons where user_id=uid and icon_id=p_icon_id;
  if chosen is null then raise exception 'You do not own that icon.'; end if;
  update public.profiles set equipped_icon=chosen, equipped_achievement_id=null where id=uid;
end; $$;
grant execute on function public.equip_owned_icon_v83(text) to authenticated;

create or replace function public.answer_icon_trade_v83(p_trade_id bigint, p_status text)
returns void language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); tr public.icon_trades%rowtype; offered public.user_icons%rowtype; requested public.user_icons%rowtype;
begin
  if uid is null then raise exception 'Not signed in.'; end if;
  select * into tr from public.icon_trades where id=p_trade_id for update;
  if not found then raise exception 'Trade not found.'; end if;
  if tr.status <> 'pending' then raise exception 'Trade is already closed.'; end if;
  if p_status='cancelled' then
    if tr.requester_id <> uid and not public.is_blank_space_admin() then raise exception 'Only requester can cancel.'; end if;
    update public.icon_trades set status='cancelled', updated_at=now() where id=p_trade_id; return;
  elsif p_status='rejected' then
    if tr.receiver_id <> uid and not public.is_blank_space_admin() then raise exception 'Only receiver can deny.'; end if;
    update public.icon_trades set status='rejected', updated_at=now() where id=p_trade_id; return;
  elsif p_status='accepted' then
    if tr.receiver_id <> uid then raise exception 'Only receiver can accept.'; end if;
    select * into offered from public.user_icons where user_id=tr.requester_id and icon_id=tr.offered_icon_id for update;
    select * into requested from public.user_icons where user_id=tr.receiver_id and icon_id=tr.requested_icon_id for update;
    if offered.icon_id is null or requested.icon_id is null then raise exception 'One of the icons is no longer owned.'; end if;
    delete from public.user_icons where user_id=tr.requester_id and icon_id=tr.offered_icon_id;
    delete from public.user_icons where user_id=tr.receiver_id and icon_id=tr.requested_icon_id;
    insert into public.user_icons(user_id, icon_id, icon, name, rarity) values(tr.receiver_id, offered.icon_id, offered.icon, offered.name, offered.rarity) on conflict do nothing;
    insert into public.user_icons(user_id, icon_id, icon, name, rarity) values(tr.requester_id, requested.icon_id, requested.icon, requested.name, requested.rarity) on conflict do nothing;
    update public.icon_trades set status='accepted', updated_at=now() where id=p_trade_id; return;
  else raise exception 'Bad trade response.';
  end if;
end; $$;
grant execute on function public.answer_icon_trade_v83(bigint, text) to authenticated;

-- Admin panel functions.
create or replace function public.admin_change_username_v83(p_old_username text, p_new_username text)
returns void language plpgsql security definer set search_path=public as $$
declare target_id uuid;
begin
 if not public.is_blank_space_admin() then raise exception 'Admin only.'; end if;
 if p_new_username !~ '^[A-Za-z0-9_]{3,20}$' then raise exception 'Invalid username.'; end if;
 select id into target_id from public.profiles where lower(username)=lower(trim(p_old_username));
 if target_id is null then raise exception 'User not found.'; end if;
 update public.profiles set username=trim(p_new_username), username_changed_at=now() where id=target_id;
end; $$;
grant execute on function public.admin_change_username_v83(text,text) to authenticated;

create or replace function public.admin_adjust_points_v83(p_username text, p_points integer, p_reason text default '')
returns void language plpgsql security definer set search_path=public as $$
declare target_id uuid; amount integer:=coalesce(p_points,0);
begin
 if not public.is_blank_space_admin() then raise exception 'Admin only.'; end if;
 select id into target_id from public.profiles where lower(username)=lower(trim(p_username));
 if target_id is null then raise exception 'User not found.'; end if;
 update public.profiles set points=greatest(0, coalesce(points,0)+amount) where id=target_id;
end; $$;
grant execute on function public.admin_adjust_points_v83(text,integer,text) to authenticated;

