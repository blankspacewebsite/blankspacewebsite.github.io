-- Blank Space v81 Supabase update
-- Safe update: adds achievements/equipped icons/game progress and fixes Delete Account.
-- This does NOT delete existing accounts, points, friends, suggestions, or messages.

alter table public.profiles
  add column if not exists equipped_icon text,
  add column if not exists equipped_achievement_id text,
  add column if not exists points integer not null default 0;

-- Game progress tracked by the website. This is reliable website-side progress,
-- not deep in-game score reading for compiled/iframe games.
create table if not exists public.game_stats (
  user_id uuid not null references public.profiles(id) on delete cascade,
  game_title text not null,
  play_count integer not null default 0,
  play_seconds integer not null default 0,
  first_played_at timestamptz not null default now(),
  last_played_at timestamptz not null default now(),
  primary key (user_id, game_title),
  constraint game_stats_title_length check (char_length(game_title) between 1 and 120),
  constraint game_stats_nonnegative check (play_count >= 0 and play_seconds >= 0)
);

create table if not exists public.user_achievements (
  user_id uuid not null references public.profiles(id) on delete cascade,
  achievement_id text not null,
  title text not null,
  description text not null,
  icon text not null,
  game_title text,
  reward_points integer not null default 0,
  earned_at timestamptz not null default now(),
  primary key (user_id, achievement_id),
  constraint achievement_id_length check (char_length(achievement_id) between 2 and 80),
  constraint achievement_title_length check (char_length(title) between 2 and 80),
  constraint achievement_description_length check (char_length(description) between 2 and 240),
  constraint achievement_icon_length check (char_length(icon) between 1 and 16),
  constraint achievement_reward_nonnegative check (reward_points >= 0 and reward_points <= 10000)
);

create table if not exists public.friend_messages (
  id bigint generated by default as identity primary key,
  friendship_id bigint not null references public.friends(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now(),
  constraint friend_messages_body_length check (char_length(body) between 1 and 500)
);

create index if not exists friend_messages_friendship_created_idx
on public.friend_messages (friendship_id, created_at);

alter table public.game_stats enable row level security;
alter table public.user_achievements enable row level security;
alter table public.friend_messages enable row level security;

