create policy "friend_messages_select_own_friendship"
on public.friend_messages
for select
to authenticated
using (
  exists (
    select 1 from public.friends f
    where f.id = friendship_id
      and f.status = 'accepted'
      and (f.requester_id = auth.uid() or f.receiver_id = auth.uid())
  )
);

create policy "friend_messages_insert_own_friendship"
on public.friend_messages
for insert
to authenticated
with check (
  sender_id = auth.uid()
  and exists (
    select 1 from public.friends f
    where f.id = friendship_id
      and f.status = 'accepted'
      and (f.requester_id = auth.uid() or f.receiver_id = auth.uid())
  )
);

create policy "friend_messages_delete_sender_or_admin"
on public.friend_messages
for delete
to authenticated
using (sender_id = auth.uid() or public.is_blank_space_admin());

-- Record reliable website-side progress for a game.
create or replace function public.record_game_progress(
  p_game_title text,
  p_open_event boolean default false,
  p_seconds integer default 0
)
returns table (
  game_title text,
  play_count integer,
  play_seconds integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  add_count integer := case when coalesce(p_open_event, false) then 1 else 0 end;
  add_seconds integer := greatest(0, coalesce(p_seconds, 0));
begin
  if uid is null then
    raise exception 'Not signed in.';
  end if;

  if p_game_title is null or char_length(trim(p_game_title)) < 1 then
    raise exception 'Game title is required.';
  end if;

  insert into public.game_stats (user_id, game_title, play_count, play_seconds)
  values (uid, trim(p_game_title), add_count, add_seconds)
  on conflict (user_id, game_title)
  do update set
    play_count = public.game_stats.play_count + excluded.play_count,
    play_seconds = public.game_stats.play_seconds + excluded.play_seconds,
    last_played_at = now();

  return query
  select gs.game_title, gs.play_count, gs.play_seconds
  from public.game_stats gs
  where gs.user_id = uid and gs.game_title = trim(p_game_title);
end;
$$;

grant execute on function public.record_game_progress(text, boolean, integer) to authenticated;

-- Award an achievement once. If it is new, also adds reward points.
create or replace function public.award_achievement(
  p_achievement_id text,
  p_title text,
  p_description text,
  p_icon text,
  p_game_title text default null,
  p_reward_points integer default 0
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  inserted_count integer := 0;
  safe_points integer := greatest(0, least(coalesce(p_reward_points, 0), 10000));
begin
  if uid is null then
    raise exception 'Not signed in.';
  end if;

  insert into public.user_achievements (user_id, achievement_id, title, description, icon, game_title, reward_points)
  values (uid, p_achievement_id, p_title, p_description, p_icon, p_game_title, safe_points)
  on conflict (user_id, achievement_id) do nothing;

  get diagnostics inserted_count = row_count;

  if inserted_count > 0 then
    update public.profiles
    set points = coalesce(points, 0) + safe_points,
        equipped_icon = coalesce(equipped_icon, p_icon),
        equipped_achievement_id = coalesce(equipped_achievement_id, p_achievement_id)
    where id = uid;
    return true;
  end if;

  return false;
end;
$$;

grant execute on function public.award_achievement(text, text, text, text, text, integer) to authenticated;

create or replace function public.equip_achievement_icon(p_achievement_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  chosen_icon text;
begin
  if uid is null then
    raise exception 'Not signed in.';
  end if;

  select ua.icon into chosen_icon
  from public.user_achievements ua
  where ua.user_id = uid
    and ua.achievement_id = p_achievement_id;

  if chosen_icon is null then
    raise exception 'You have not unlocked that icon yet.';
  end if;

  update public.profiles
  set equipped_icon = chosen_icon,
      equipped_achievement_id = p_achievement_id
  where id = uid;
end;
$$;

grant execute on function public.equip_achievement_icon(text) to authenticated;

-- Public leaderboard now includes equipped icon and still hides admins.
create or replace function public.get_public_leaderboard(max_rows integer default 100)
returns table (
  id uuid,
  username text,
  avatar_url text,
  points integer,
  equipped_icon text
)
language sql
security definer
set search_path = public
as $$
  select p.id, p.username, p.avatar_url, p.points, p.equipped_icon
  from public.profiles p
  where not exists (
    select 1
    from public.admin_users a
    where a.user_id = p.id
  )
  order by p.points desc, lower(p.username) asc
  limit greatest(1, least(coalesce(max_rows, 100), 100));
$$;

grant execute on function public.get_public_leaderboard(integer) to anon, authenticated;

-- Corrected account deletion helper: handles whichever optional tables/columns exist.
create or replace function public.delete_rows_for_account_if_column_exists_v2(
  p_table_name text,
  p_column_name text,
  p_account_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if to_regclass(format('public.%I', p_table_name)) is not null
     and exists (
       select 1
       from information_schema.columns c
       where c.table_schema = 'public'
         and c.table_name = p_table_name
         and c.column_name = p_column_name
     )
  then
    execute format('delete from public.%I where %I = $1', p_table_name, p_column_name)
    using p_account_id;
  end if;
end;
$$;

