create or replace function public.is_blank_space_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and (
        lower(trim(coalesce(p.rank, 'member'))) = 'owner'
        or lower(trim(coalesce(p.username, ''))) in ('owner', 'admin')
      )
  );
$$;

grant execute on function public.is_blank_space_owner() to anon, authenticated;

