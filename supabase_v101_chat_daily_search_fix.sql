drop function if exists public.get_daily_reward_status_v99();

create function public.get_daily_reward_status_v99()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  r public.daily_rewards%rowtype;
  v_next integer := 1;
  v_can boolean := true;
  v_msg text := 'Ready.';
begin
  if v_uid is null then
    return jsonb_build_object(
      'ok', false,
      'signed_in', false,
      'can_claim', false,
      'next_day', 1,
      'message', 'Not signed in. Sign in on Account, then press Refresh on Daily Rewards.'
    );
  end if;

  select * into r from public.daily_rewards where user_id = v_uid;

  if r.user_id is null then
    return jsonb_build_object(
      'ok', true,
      'signed_in', true,
      'can_claim', true,
      'next_day', 1,
      'message', 'Ready for Day 1.',
      'streak_day', 0
    );
  end if;

  if r.last_claim_date = current_date then
    v_can := false;
    v_next := least(coalesce(r.streak_day, 0) + 1, 7);
    v_msg := 'Already claimed today.';
  elsif r.reset_wait_until is not null and current_date < r.reset_wait_until then
    v_can := false;
    v_next := 1;
    v_msg := 'You missed a day. Come back tomorrow to restart.';
  elsif r.last_claim_date is not null
        and r.last_claim_date < current_date - 1
        and r.reset_wait_until is null then
    v_can := false;
    v_next := 1;
    v_msg := 'You missed a day. Come back tomorrow to restart.';
  elsif r.last_claim_date = current_date - 1 then
    v_next := least(coalesce(r.streak_day, 0) + 1, 7);
  else
    v_next := 1;
  end if;

  return jsonb_build_object(
    'ok', true,
    'signed_in', true,
    'can_claim', v_can,
    'next_day', v_next,
    'message', v_msg,
    'streak_day', coalesce(r.streak_day, 0),
    'last_claim_date', r.last_claim_date,
    'reset_wait_until', r.reset_wait_until
  );
end;
$$;

grant execute on function public.get_daily_reward_status_v99() to anon, authenticated;

drop function if exists public.claim_daily_reward_v99();

create function public.claim_daily_reward_v99()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  r public.daily_rewards%rowtype;
  v_day integer := 1;
  v_points integer := 1;
begin
  if v_uid is null then
    return jsonb_build_object(
      'ok', false,
      'signed_in', false,
      'message', 'Not signed in. Sign in on Account, then press Refresh on Daily Rewards.'
    );
  end if;

  select * into r
  from public.daily_rewards
  where user_id = v_uid
  for update;

  if r.user_id is not null then
    if r.last_claim_date = current_date then
      return jsonb_build_object('ok', false, 'signed_in', true, 'message', 'Already claimed today.', 'day', r.streak_day);
    end if;

    if r.reset_wait_until is not null and current_date < r.reset_wait_until then
      return jsonb_build_object('ok', false, 'signed_in', true, 'message', 'You missed a day. Come back tomorrow to restart.');
    end if;

    if r.last_claim_date is not null
       and r.last_claim_date < current_date - 1
       and (r.reset_wait_until is null or r.reset_wait_until < current_date) then
      update public.daily_rewards
      set streak_day = 0,
          reset_wait_until = current_date + 1,
          updated_at = now()
      where user_id = v_uid;

      return jsonb_build_object('ok', false, 'signed_in', true, 'message', 'You missed a day. Come back tomorrow to restart at Day 1.');
    end if;

    if r.last_claim_date = current_date - 1 then
      v_day := least(coalesce(r.streak_day, 0) + 1, 7);
    else
      v_day := 1;
    end if;
  end if;

  v_points := case v_day
    when 1 then 1
    when 2 then 2
    when 3 then 3
    when 4 then 4
    when 5 then 5
    when 6 then 8
    else 10
  end;

  insert into public.daily_rewards(user_id, streak_day, last_claim_date, reset_wait_until, updated_at)
  values(v_uid, v_day, current_date, null, now())
  on conflict(user_id) do update set
    streak_day = excluded.streak_day,
    last_claim_date = excluded.last_claim_date,
    reset_wait_until = null,
    updated_at = now();

  perform set_config('blank_space.allow_points_update', '1', true);

  update public.profiles
  set points = coalesce(points, 0) + v_points
  where id = v_uid;

  return jsonb_build_object(
    'ok', true,
    'signed_in', true,
    'day', v_day,
    'points_awarded', v_points,
    'message', 'Claimed Day ' || v_day || ' for ' || v_points || ' point(s).'
  );
end;
$$;

grant execute on function public.claim_daily_reward_v99() to anon, authenticated;

