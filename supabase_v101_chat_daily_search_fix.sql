drop function if exists public.owner_get_user_chat_view_v95(text, integer);
drop function if exists public.owner_get_user_chat_view_v99(text, integer);

create function public.owner_get_user_chat_view_v95(
  p_username text,
  p_limit integer default 250
)
returns table(
  chat_type text,
  chat_name text,
  sender_username text,
  is_target_sender boolean,
  body text,
  image_url text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_target uuid;
  v_limit integer := greatest(1, least(coalesce(p_limit, 250), 500));
begin
  if auth.uid() is null then
    raise exception 'Sign in first.';
  end if;

  if not public.is_blank_space_owner() then
    raise exception 'Owner only.';
  end if;

  select p.id
  into v_target
  from public.profiles p
  where lower(trim(p.username)) = lower(trim(coalesce(p_username, '')))
  order by p.created_at asc nulls last, p.id asc
  limit 1;

  if v_target is null then
    raise exception 'User not found.';
  end if;

  return query
  with friend_rows as (
    select
      'friend'::text as chat_type,
      (
        '@' ||
        coalesce(
          case
            when f.requester_id = v_target then receiver_profile.username
            else requester_profile.username
          end,
          'friend'
        )
      )::text as chat_name,
      coalesce(sender_profile.username, 'Unknown')::text as sender_username,
      (fm.sender_id = v_target)::boolean as is_target_sender,
      coalesce(fm.body, '')::text as body,
      fm.image_url::text as image_url,
      fm.created_at::timestamptz as created_at
    from public.friend_messages fm
    join public.friends f on f.id = fm.friendship_id
    left join public.profiles sender_profile on sender_profile.id = fm.sender_id
    left join public.profiles receiver_profile on receiver_profile.id = f.receiver_id
    left join public.profiles requester_profile on requester_profile.id = f.requester_id
    where (f.requester_id = v_target or f.receiver_id = v_target)
      and coalesce(f.status, 'accepted') = 'accepted'
  ),
  group_rows as (
    select
      'group'::text as chat_type,
      coalesce(gc.name, 'Group Chat')::text as chat_name,
      coalesce(sender_profile.username, 'Unknown')::text as sender_username,
      (gm.sender_id = v_target)::boolean as is_target_sender,
      coalesce(gm.body, '')::text as body,
      gm.image_url::text as image_url,
      gm.created_at::timestamptz as created_at
    from public.group_chat_messages gm
    join public.group_chat_members gcm
      on gcm.group_id = gm.group_id
     and gcm.user_id = v_target
    join public.group_chats gc on gc.id = gm.group_id
    left join public.profiles sender_profile on sender_profile.id = gm.sender_id
  )
  select *
  from (
    select * from friend_rows
    union all
    select * from group_rows
  ) all_rows
  order by all_rows.created_at desc
  limit v_limit;
end;
$$;

grant execute on function public.owner_get_user_chat_view_v95(text, integer) to authenticated;

create function public.owner_get_user_chat_view_v99(
