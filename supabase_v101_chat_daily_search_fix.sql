drop function if exists public.search_achievements_v99(text, text, text, integer);

create function public.search_achievements_v99(
  p_search text default '',
  p_game_title text default null,
  p_locked_filter text default 'all',
  p_limit integer default 250
)
returns table(
  achievement_id text,
  title text,
  description text,
  icon text,
  game_title text,
  stat text,
  target integer,
  reward_points integer,
  difficulty text,
  unlocked boolean,
  earned_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_search text := lower(trim(coalesce(p_search, '')));
  v_game text := nullif(trim(coalesce(p_game_title, '')), '');
  v_filter text := lower(trim(coalesce(p_locked_filter, 'all')));
  v_limit integer := greatest(1, least(coalesce(p_limit, 250), 500));
begin
  if v_uid is null then
    raise exception 'Sign in first.';
  end if;

  return query
  select
    c.achievement_id,
    coalesce(c.title, 'Achievement') as title,
    coalesce(c.description, '') as description,
    coalesce(c.icon, '🏆') as icon,
    c.game_title,
    c.stat,
    c.target,
    greatest(0, coalesce(c.reward_points, 0)) as reward_points,
    coalesce(c.difficulty, 'medium') as difficulty,
    (ua.achievement_id is not null) as unlocked,
    ua.earned_at
  from public.achievement_catalog c
  left join public.user_achievements ua
    on ua.user_id = v_uid
   and ua.achievement_id = c.achievement_id
  where c.achievement_id is not null
    and (v_game is null or c.game_title = v_game)
    and (
      v_search = ''
      or lower(coalesce(c.title, '')) like '%' || v_search || '%'
      or lower(coalesce(c.description, '')) like '%' || v_search || '%'
      or lower(coalesce(c.game_title, '')) like '%' || v_search || '%'
      or lower(coalesce(c.difficulty, '')) like '%' || v_search || '%'
      or lower(coalesce(c.stat, '')) like '%' || v_search || '%'
      or lower(coalesce(c.achievement_id, '')) like '%' || v_search || '%'
    )
    and (
      v_filter = 'all'
      or (v_filter in ('unlocked', 'earned') and ua.achievement_id is not null)
      or (v_filter in ('locked', 'missing') and ua.achievement_id is null)
    )
  order by
    c.game_title,
    c.target nulls last,
    c.title
  limit v_limit;
end;
$$;

grant execute on function public.search_achievements_v99(text, text, text, integer) to authenticated;

