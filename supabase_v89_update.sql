-- 3) Admin rank and moderation RPC
-- ===============================
create or replace function public.admin_set_rank_v89(p_username text, p_rank text, p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin uuid := auth.uid();
  v_target public.profiles%rowtype;
  v_rank text := lower(trim(coalesce(p_rank,'member')));
begin
  if v_admin is null or not public.is_blank_space_admin() then raise exception 'Admin only.'; end if;
  if v_rank not in ('admin','manager','tester','member') then raise exception 'Invalid rank.'; end if;
  select * into v_target from public.profiles where lower(username)=lower(trim(coalesce(p_username,''))) limit 1;
  if v_target.id is null then raise exception 'User not found.'; end if;
  perform set_config('blank_space.allow_rank_update','1',true);
  update public.profiles set rank = v_rank where id = v_target.id;
  if v_rank = 'admin' then
    insert into public.admin_users(user_id) values (v_target.id) on conflict (user_id) do nothing;
  else
    delete from public.admin_users where user_id = v_target.id;
  end if;
  perform public.log_admin_action(v_target.id, v_target.username, 'set_rank:' || v_rank, p_reason);
  return jsonb_build_object('ok', true, 'username', v_target.username, 'rank', v_rank);
end;
$$;

grant execute on function public.admin_set_rank_v89(text, text, text) to authenticated;

create or replace function public.admin_moderate_user_v89(p_username text, p_action text, p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin uuid := auth.uid();
  v_target public.profiles%rowtype;
  v_action text := lower(trim(coalesce(p_action,'')));
begin
  if v_admin is null or not public.is_blank_space_admin() then raise exception 'Admin only.'; end if;
  select * into v_target from public.profiles where lower(username)=lower(trim(coalesce(p_username,''))) limit 1;
  if v_target.id is null then raise exception 'User not found.'; end if;
  perform set_config('blank_space.allow_moderation_update','1',true);
  if v_action = 'mute_chat' then
    update public.profiles set chat_muted_until = now() + interval '7 days' where id = v_target.id;
  elsif v_action = 'unmute_chat' then
    update public.profiles set chat_muted_until = null where id = v_target.id;
  elsif v_action = 'ban_chat' then
    update public.profiles set is_banned = true, ban_reason = nullif(trim(coalesce(p_reason,'')),'') where id = v_target.id;
  elsif v_action = 'unban_chat' then
    update public.profiles set is_banned = false, ban_reason = null where id = v_target.id;
  elsif v_action = 'reset_achievements_keep_points' then
    delete from public.user_achievements where user_id = v_target.id;
  elsif v_action = 'clear_messages' then
    if to_regclass('public.friend_messages') is not null then
      delete from public.friend_messages where sender_id = v_target.id;
    end if;
    if to_regclass('public.group_chat_messages') is not null then
      delete from public.group_chat_messages where sender_id = v_target.id;
    end if;
  else
    raise exception 'Unknown moderation action.';
  end if;
  perform public.log_admin_action(v_target.id, v_target.username, v_action, p_reason);
  return jsonb_build_object('ok', true, 'username', v_target.username, 'action', v_action);
end;
$$;

grant execute on function public.admin_moderate_user_v89(text, text, text) to authenticated;

create or replace function public.enforce_chat_moderation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_is_banned boolean;
  v_muted_until timestamptz;
begin
  select is_banned, chat_muted_until into v_is_banned, v_muted_until from public.profiles where id = new.sender_id;
  if coalesce(v_is_banned,false) then raise exception 'You are banned from chat.'; end if;
  if v_muted_until is not null and v_muted_until > now() then raise exception 'You are muted from chat until %.', v_muted_until; end if;
  return new;
end;
$$;

do $$ begin
  if to_regclass('public.friend_messages') is not null then
    execute 'drop trigger if exists friend_messages_moderation_trigger on public.friend_messages';
    execute 'create trigger friend_messages_moderation_trigger before insert on public.friend_messages for each row execute function public.enforce_chat_moderation()';
  end if;
end $$;

