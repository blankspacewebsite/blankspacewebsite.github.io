create or replace function public.leave_group_chat(p_group_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_my_role text;
  v_new_owner uuid;
begin
  if v_uid is null then
    raise exception 'Not signed in.';
  end if;

  select role into v_my_role
  from public.group_chat_members
  where group_id = p_group_id and user_id = v_uid;

  if v_my_role is null then
    raise exception 'You are not in this group chat.';
  end if;

  if v_my_role = 'owner' then
    select user_id into v_new_owner
    from public.group_chat_members
    where group_id = p_group_id and user_id <> v_uid
    order by joined_at asc
    limit 1;

    if v_new_owner is null then
      delete from public.group_chats where id = p_group_id;
      return jsonb_build_object('ok', true, 'deleted_group', true);
    end if;

    update public.group_chat_members
    set role = 'owner'
    where group_id = p_group_id and user_id = v_new_owner;

    update public.group_chats
    set owner_id = v_new_owner, updated_at = now()
    where id = p_group_id;
  end if;

  delete from public.group_chat_members
  where group_id = p_group_id and user_id = v_uid;

  return jsonb_build_object('ok', true, 'left_group', true, 'new_owner', v_new_owner);
end;
$$;

create or replace function public.delete_group_chat(p_group_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'Not signed in.';
  end if;

  if not public.can_manage_group_chat(p_group_id, v_uid) then
    raise exception 'Only a group owner or group admin can delete this group.';
  end if;

  delete from public.group_chats where id = p_group_id;
  return jsonb_build_object('ok', true, 'deleted_group', true);
end;
$$;

-- 6) Read helpers for the website.
create or replace function public.get_my_group_chats()
returns table (
  id bigint,
  name text,
  owner_id uuid,
  my_role text,
  member_count bigint,
  last_message_body text,
  last_message_at timestamptz,
  updated_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Not signed in.';
  end if;

  return query
  select
    g.id,
    g.name,
    g.owner_id,
    m.role as my_role,
    (select count(*) from public.group_chat_members cm where cm.group_id = g.id) as member_count,
    (select gm.body from public.group_chat_messages gm where gm.group_id = g.id order by gm.created_at desc limit 1) as last_message_body,
    (select gm.created_at from public.group_chat_messages gm where gm.group_id = g.id order by gm.created_at desc limit 1) as last_message_at,
    g.updated_at
  from public.group_chats g
  join public.group_chat_members m on m.group_id = g.id and m.user_id = auth.uid()
  order by coalesce(
    (select max(gm2.created_at) from public.group_chat_messages gm2 where gm2.group_id = g.id),
    g.updated_at
  ) desc;
end;
$$;

create or replace function public.get_group_chat_members(p_group_id bigint)
returns table (
  user_id uuid,
  username text,
  avatar_url text,
  role text,
  joined_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Not signed in.';
  end if;

  if not public.is_group_chat_member(p_group_id, auth.uid()) then
    raise exception 'You are not a member of this group chat.';
  end if;

  return query
  select
    m.user_id,
    p.username,
    p.avatar_url,
    m.role,
    m.joined_at
  from public.group_chat_members m
  join public.profiles p on p.id = m.user_id
  where m.group_id = p_group_id
  order by
    case m.role when 'owner' then 1 when 'admin' then 2 else 3 end,
    lower(p.username) asc;
end;
$$;

