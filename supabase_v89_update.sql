create function public.get_group_chat_messages(p_group_id bigint, p_limit integer default 50)
returns table (
  id bigint,
  group_id bigint,
  sender_id uuid,
  sender_username text,
  sender_avatar_url text,
  sender_rank text,
  body text,
  image_url text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Not signed in.';
  end if;

  if not public.is_group_chat_member(p_group_id, auth.uid()) then
    raise exception 'You are not a member of this group chat.';
  end if;

  return query
  select
    gm.id,
    gm.group_id,
    gm.sender_id,
    p.username as sender_username,
    p.avatar_url as sender_avatar_url,
    coalesce(p.rank, 'member') as sender_rank,
    gm.body,
    gm.image_url,
    gm.created_at
  from public.group_chat_messages gm
  join public.profiles p on p.id = gm.sender_id
  where gm.group_id = p_group_id
  order by gm.created_at desc
  limit greatest(1, least(coalesce(p_limit, 50), 100));
end;
$$;

