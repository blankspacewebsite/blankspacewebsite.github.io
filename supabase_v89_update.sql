create function public.get_public_leaderboard(max_rows integer default 100)
returns table(id uuid, username text, avatar_url text, points integer, equipped_icon text, rank text)
language sql
security definer
set search_path = public
as $$
  select p.id, p.username, p.avatar_url, p.points, p.equipped_icon, coalesce(p.rank,'member') as rank
  from public.profiles p
  order by p.points desc, lower(p.username) asc
  limit greatest(1, least(coalesce(max_rows,100),100));
$$;

