-- 2) Profile guard with safe rank edits
-- ===================================
create or replace function public.profiles_update_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.id is distinct from old.id then raise exception 'Profile ID cannot be changed.'; end if;
  if new.created_at is distinct from old.created_at then raise exception 'Profile creation time cannot be changed.'; end if;
  if coalesce(current_setting('blank_space.allow_points_update', true), '') <> '1' and new.points is distinct from old.points then
    raise exception 'Points can only be changed by an approved Blank Space server function.';
  end if;
  if coalesce(current_setting('blank_space.allow_rank_update', true), '') <> '1' and new.rank is distinct from old.rank then
    raise exception 'Rank can only be changed by an approved Blank Space admin function.';
  end if;
  if coalesce(current_setting('blank_space.allow_moderation_update', true), '') <> '1' and (new.is_banned is distinct from old.is_banned or new.ban_reason is distinct from old.ban_reason or new.chat_muted_until is distinct from old.chat_muted_until) then
    raise exception 'Moderation fields can only be changed by an approved Blank Space admin function.';
  end if;
  if new.username is distinct from old.username then
    if coalesce(current_setting('blank_space.allow_username_update', true), '') <> '1' then
      if old.username_last_changed_at is not null and old.username_last_changed_at > now() - interval '7 days' then
        raise exception 'You can only change your username once every 7 days.';
      end if;
    end if;
    new.username_last_changed_at := now();
  elsif new.username_last_changed_at is distinct from old.username_last_changed_at then
    raise exception 'Username timer cannot be changed directly.';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_update_guard_trigger on public.profiles;
create trigger profiles_update_guard_trigger before update on public.profiles for each row execute function public.profiles_update_guard();

