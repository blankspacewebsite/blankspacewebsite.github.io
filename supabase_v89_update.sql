create table if not exists public.group_chats (
  id bigint generated by default as identity primary key,
  name text not null,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint group_chats_name_length check (char_length(trim(name)) between 1 and 40)
);

create table if not exists public.group_chat_members (
  group_id bigint not null references public.group_chats(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member',
  invited_by uuid references public.profiles(id) on delete set null,
  joined_at timestamptz not null default now(),
  primary key (group_id, user_id),
  constraint group_chat_members_role_check check (role in ('owner', 'admin', 'member'))
);

create table if not exists public.group_chat_messages (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.group_chats(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text,
  image_url text,
  created_at timestamptz not null default now(),
  constraint group_chat_messages_content_check check (
    (body is not null and char_length(trim(body)) between 1 and 1000)
    or
    (image_url is not null and char_length(trim(image_url)) between 1 and 2000)
  )
);

create index if not exists group_chats_owner_idx on public.group_chats(owner_id);
create index if not exists group_chat_members_user_idx on public.group_chat_members(user_id);
create index if not exists group_chat_messages_group_created_idx on public.group_chat_messages(group_id, created_at desc);
create index if not exists group_chat_messages_sender_idx on public.group_chat_messages(sender_id);

-- 2) Helper functions used by RLS. These avoid recursive policy errors.
create or replace function public.is_group_chat_member(p_group_id bigint, p_user_id uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.group_chat_members m
    where m.group_id = p_group_id
      and m.user_id = p_user_id
  );
$$;

create or replace function public.can_manage_group_chat(p_group_id bigint, p_user_id uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.group_chat_members m
    where m.group_id = p_group_id
      and m.user_id = p_user_id
      and m.role in ('owner', 'admin')
  );
$$;

create or replace function public.are_accepted_friends(p_user_a uuid, p_user_b uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select p_user_a = p_user_b or exists (
    select 1
    from public.friends f
    where f.status = 'accepted'
      and (
        (f.requester_id = p_user_a and f.receiver_id = p_user_b)
        or
        (f.requester_id = p_user_b and f.receiver_id = p_user_a)
      )
  );
$$;

