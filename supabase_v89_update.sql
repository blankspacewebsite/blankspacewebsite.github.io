create or replace function public.create_group_chat(p_name text, p_member_ids uuid[] default '{}')
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_name text := trim(coalesce(p_name, ''));
  v_group_id bigint;
  v_member uuid;
  v_added integer := 0;
begin
  if v_uid is null then
    raise exception 'Not signed in.';
  end if;

  if char_length(v_name) < 1 or char_length(v_name) > 40 then
    raise exception 'Group chat name must be 1 to 40 characters.';
  end if;

  insert into public.group_chats(name, owner_id)
  values (v_name, v_uid)
  returning id into v_group_id;

  insert into public.group_chat_members(group_id, user_id, role, invited_by)
  values (v_group_id, v_uid, 'owner', v_uid)
  on conflict (group_id, user_id) do update set role = 'owner';

  foreach v_member in array coalesce(p_member_ids, '{}'::uuid[]) loop
    if v_member is not null
       and v_member <> v_uid
       and public.are_accepted_friends(v_uid, v_member) then
      insert into public.group_chat_members(group_id, user_id, role, invited_by)
      values (v_group_id, v_member, 'member', v_uid)
      on conflict do nothing;
      v_added := v_added + 1;
    end if;
  end loop;

  return jsonb_build_object('ok', true, 'group_id', v_group_id, 'added_members', v_added);
end;
$$;

create or replace function public.create_group_chat_by_usernames(p_name text, p_usernames text[] default '{}')
returns jsonb
