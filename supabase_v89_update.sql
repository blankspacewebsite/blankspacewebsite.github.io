create or replace function public.send_group_chat_message(
  p_group_id bigint,
  p_body text default null,
  p_image_url text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_body text := nullif(trim(coalesce(p_body, '')), '');
  v_image_url text := nullif(trim(coalesce(p_image_url, '')), '');
  v_message_id bigint;
  v_created_at timestamptz;
begin
  if v_uid is null then
    raise exception 'Not signed in.';
  end if;

  if not public.is_group_chat_member(p_group_id, v_uid) then
    raise exception 'You are not a member of this group chat.';
  end if;

  if v_body is null and v_image_url is null then
    raise exception 'Message cannot be empty.';
  end if;

  if v_body is not null and char_length(v_body) > 1000 then
    raise exception 'Message is too long.';
  end if;

  insert into public.group_chat_messages(group_id, sender_id, body, image_url)
  values (p_group_id, v_uid, v_body, v_image_url)
  returning id, created_at into v_message_id, v_created_at;

  update public.group_chats
  set updated_at = now()
  where id = p_group_id;

  return jsonb_build_object('ok', true, 'message_id', v_message_id, 'created_at', v_created_at);
end;
$$;

