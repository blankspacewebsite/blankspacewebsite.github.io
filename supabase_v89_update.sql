alter table public.profiles add column if not exists ban_reason text;
alter table public.profiles add column if not exists chat_muted_until timestamptz;
update public.profiles set rank = 'member' where rank is null or lower(rank) not in ('admin','manager','tester','member');

create table if not exists public.admin_users (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_blank_space_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users a where a.user_id = auth.uid())
     or exists (select 1 from public.profiles p where p.id = auth.uid() and lower(coalesce(p.rank,'member')) = 'admin');
$$;

grant execute on function public.is_blank_space_admin() to anon, authenticated;

create table if not exists public.admin_actions_log (
  id bigint generated by default as identity primary key,
  admin_id uuid references public.profiles(id) on delete set null,
  target_user_id uuid references public.profiles(id) on delete set null,
  target_username text,
  action text not null,
  reason text,
  created_at timestamptz not null default now()
);

alter table public.admin_actions_log enable row level security;
drop policy if exists "admin_actions_admin_select" on public.admin_actions_log;
create policy "admin_actions_admin_select" on public.admin_actions_log for select to authenticated using (public.is_blank_space_admin());

grant select, insert on table public.admin_actions_log to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create or replace function public.log_admin_action(p_target_user_id uuid, p_target_username text, p_action text, p_reason text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.admin_actions_log(admin_id, target_user_id, target_username, action, reason)
